// customMockProvider returns a valid JSON for our test and injects the REDACTED token
type customMockProvider struct{}

func (m *customMockProvider) Complete(ctx context.Context, req CompletionRequest) (CompletionResponse, error) {
	// Find the token in the prompt
	prompt := req.Messages[0].Content
	
	// The prompt should have "Message: Suspicious login from <REDACTED:"
	// Let's extract it
	tokenStart := "<REDACTED:"
	startIdx := 0
	for i := 0; i < len(prompt); i++ {
		if i+len(tokenStart) <= len(prompt) && prompt[i:i+len(tokenStart)] == tokenStart {
			startIdx = i
			break
		}
	}
	
	token := "<REDACTED:unknown>"
	if startIdx > 0 {
		endIdx := startIdx
		for i := startIdx; i < len(prompt); i++ {
			if prompt[i] == '>' {
				endIdx = i + 1
				break
			}
		}
		if endIdx > startIdx {
			token = prompt[startIdx:endIdx]
		}
	}

	jsonResponse := `{
		"incident_id": "INC-123",
		"severity": "HIGH",
		"summary": "Suspicious login from ` + token + `",
		"root_cause": "Compromised credentials for ` + token + `",
		"mitre_techniques": ["T1078"],
		"attack_path": ["User -> VPN -> Server"],
		"choke_points": ["VPN Gateway"],
		"recommended_remediations": ["Reset passwords", "Enable MFA"],
		"confidence": 0.95
	}`

	return CompletionResponse{
		Content: jsonResponse,
		Tokens: 100,
	}, nil
}

